import PDFDocument from "pdfkit";

const formatCurrency = (amount) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 2
  }).format(amount || 0);

/**
 * Lightweight PDF via pdfkit (no Chromium). Returns a Buffer.
 */
export const buildPdfReport = async (report, type = "Monthly", dateParam = "") => {
  const summary = report.summary || { income: 0, expense: 0, transfer: 0 };
  const netSavings = report.netSavings ?? (summary.income || 0) - (summary.expense || 0);
  const cashBalance = report.cashBalance || 0;
  const bankBalances = report.bankBalances || [];
  const bankWiseExpenses = report.bankWiseExpenses || [];
  const categoryBreakdown = report.categoryBreakdown || report.categoryExpenses || [];
  const monthYearHeader = dateParam || new Date().toLocaleDateString("en-IN", { month: "long", year: "numeric" });

  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: "A4" });
    const chunks = [];
    doc.on("data", (c) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.fontSize(18).fillColor("#0f172a").text("MoneyMatrix Report", { align: "left" });
    doc.moveDown(0.3);
    doc.fontSize(11).fillColor("#64748b").text(`${type} · ${monthYearHeader}`);
    doc.moveDown(1);

    doc.fontSize(13).fillColor("#0f172a").text("Summary");
    doc.moveDown(0.4);
    doc.fontSize(11).fillColor("#1e293b");
    doc.text(`Income:   ${formatCurrency(summary.income)}`);
    doc.text(`Expense:  ${formatCurrency(summary.expense)}`);
    doc.text(`Transfer: ${formatCurrency(summary.transfer)}`);
    doc.text(`Net:      ${formatCurrency(netSavings)}`);
    doc.text(`Cash:     ${formatCurrency(cashBalance)}`);
    doc.moveDown(1);

    if (bankBalances.length) {
      doc.fontSize(13).fillColor("#0f172a").text("Bank Balances");
      doc.moveDown(0.4);
      doc.fontSize(11).fillColor("#1e293b");
      bankBalances.forEach((b) => {
        doc.text(`${b.bankName || "Bank"}: ${formatCurrency(b.currentBalance)}`);
      });
      doc.moveDown(1);
    }

    if (bankWiseExpenses.length) {
      doc.fontSize(13).fillColor("#0f172a").text("Bank-wise Expenses");
      doc.moveDown(0.4);
      doc.fontSize(11).fillColor("#1e293b");
      bankWiseExpenses.forEach((b) => {
        doc.text(`${b.bankName || "Bank"}: ${formatCurrency(b.total)}`);
      });
      doc.moveDown(1);
    }

    if (categoryBreakdown.length) {
      doc.fontSize(13).fillColor("#0f172a").text("Category Breakdown");
      doc.moveDown(0.4);
      doc.fontSize(11).fillColor("#1e293b");
      categoryBreakdown.slice(0, 20).forEach((c) => {
        const name = c.name || c.categoryName || c._id || "Category";
        doc.text(`${name}: ${formatCurrency(c.total || c.amount)}`);
      });
    }

    doc.moveDown(2);
    doc.fontSize(9).fillColor("#94a3b8").text("Generated by MoneyMatrix", { align: "center" });
    doc.end();
  });
};
